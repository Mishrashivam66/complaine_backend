"use strict";

const mongoose = require("mongoose");

// ==========================================
// DYNAMIC ACADEMIC BLOCK MODEL
// ==========================================

const blockSchema = new mongoose.Schema(
  {
    code: {
      type: String,
      required: true,
      unique: true,
      trim: true,
      uppercase: true,
      maxlength: 12,
      match: /^[A-Z0-9][A-Z0-9_-]*$/,
    },

    name: {
      type: String,
      required: true,
      trim: true,
      maxlength: 100,
    },

    description: {
      type: String,
      trim: true,
      default: "",
    },

    isActive: {
      type: Boolean,
      default: true,
    },

    isDeleted: {
      type: Boolean,
      default: false,
    },
  },
  {
    timestamps: true,
  },
);

module.exports = mongoose.model("Block", blockSchema);
